package com.example.onlineschool.model;

import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import lombok.Data;

/**
 * Сущность, представляющая преподавателя.
 
 * Содержит персональные и профессиональные данные преподавателя,
 * включая контактную информацию и квалификационные характеристики.
 
 *
 * @see Entity
 * @see Data
 */
@Entity
@Data
public class Teacher {

    /**
     * Уникальный идентификатор преподавателя в системе.
     
     * Автоматически генерируется базой данных при создании записи.
     * Используется в качестве первичного ключа таблицы.
     
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Integer id;

    /**
     * Имя преподавателя.
     
     * Обязательное поле. Должно содержать только буквенные символы.
     
     */
    private String firstName;

    /**
     * Фамилия преподавателя.
     
     * Обязательное поле. Должно содержать только буквенные символы.
     * Используется для официального именования преподавателя.
     
     */
    private String lastName;

    /**
     * Отчество преподавателя.
     
     * Может отсутствовать для иностранных преподавателей.
     * При наличии должно содержать только буквенные символы.
     
     */
    private String surname;

    /**
     * Корпоративная электронная почта преподавателя.
     
     * Должна быть уникальной для каждого преподавателя.
     * Должна соответствовать стандартному формату email.
     * Используется для официальной коммуникации.
     
     */
    private String email;

    /**
     * Контактный телефон преподавателя.
     
     * Должен содержать номер в международном формате.
     * Используется для экстренной связи.
     
     */
    private String phone;

    /**
     * Основная специализация преподавателя.
     
     * Определяет область профессиональной компетенции.
     * Примеры значений: "Математика", "Программирование", "Физика".
     
     */
    private String specialization;

    /**
     * Опыт преподавательской работы.
     
     * Указывается в полных годах.
     * Должно быть положительным числом.
     * Включает только опыт работы по специальности.
     
     */
    private Integer experience;
}